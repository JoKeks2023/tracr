const german = typeof navigator !== "undefined" && (navigator.language ?? "").toLowerCase().startsWith("de");
export const lang: "de" | "en" = german ? "de" : "en";
/** BCP 47 locale for dates and numbers. */
export const locale = german ? "de-DE" : "en-GB";

export function t(key: Key, vars?: Record<string, string | number>): string {
  let text: string = (german ? de[key] : undefined) ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}
